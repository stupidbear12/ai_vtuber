def build_messages(conversation):
    """대화 리스트를 messages 형식으로 변환"""
    messages = [{"role": "system", "content": SYSTEM_PROMPT}]
    for user_msg, assistant_msg in conversation:
        messages.append({"role": "user", "content": user_msg})
        messages.append({"role": "assistant", "content": assistant_msg})
    return {"messages": messages}


def main():
    output_file = os.path.join(TRAINING_DIR, "sion_multiturn.jsonl")

    entries = []
    for conv in MULTITURN_CONVERSATIONS:
        entry = build_messages(conv)
        entries.append(entry)

    # 각 멀티턴 대화에서 부분 대화도 추출 (prefix 학습)
    # 예: 4턴 대화 → 1턴, 2턴, 3턴, 4턴 버전 생성
    augmented = []
    for conv in MULTITURN_CONVERSATIONS:
        if len(conv) >= 3:
            for end_idx in range(2, len(conv)):
                partial = conv[:end_idx]
                augmented.append(build_messages(partial))

    entries.extend(augmented)

    # 셔플
    random.seed(42)
    random.shuffle(entries)

    with open(output_file, "w", encoding="utf-8") as f:
        for entry in entries:
            f.write(json.dumps(entry, ensure_ascii=False) + "\n")

    print(f"생성 완료: {len(entries)}건 → {output_file}")
    print(f"  - 원본 대화: {len(MULTITURN_CONVERSATIONS)}건")
    print(f"  - 부분 대화 증강: {len(augmented)}건")


if __name__ == "__main__":
    main()
