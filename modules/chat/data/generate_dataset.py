def pick(*pools):
    return random.choice(list(pools[0]) if len(pools) == 1 else pools)


def build(emotion: str, opener: str, body: str, closer: str = "") -> str:
    tag = f"[감정:{emotion}]"
    parts = [opener, body]
    if closer:
        parts.append(closer)
    return f"{tag} {' '.join(p for p in parts if p)}"


