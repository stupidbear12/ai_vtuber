def main():
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)

    all_data: list[dict] = []
    all_data += gen_daily_greetings(140)
    all_data += gen_empathy(120)
    all_data += gen_music(110)
    all_data += gen_broadcast(80)
    all_data += gen_gaming(110)
    all_data += gen_advice(120)
    all_data += gen_humor(90)
    all_data += gen_compliments_and_thanks(90)
    all_data += gen_knowledge_curious(80)
    all_data += gen_self_intro(70)
    all_data += gen_trend_reaction(130)
    all_data += gen_late_night(90)
    all_data += gen_troll_response(70)
    all_data += gen_multi_turn_pairs(130)  # 멀티턴 포맷 (1 entry per scenario)
    all_data += gen_broadcast_chat_short(70)

    # 감정 태그 누락 검증 및 통계
    emotion_counter: dict[str, int] = defaultdict(int)
    category_counter: dict[str, int] = defaultdict(int)
    missing_tag = 0
    valid_emotions = {"happy", "sad", "surprised", "thinking", "excited", "calm", "worried", "angry", "love", "shy"}
    emotion_re = re.compile(r"^\[감정:(\w+)\]")

    for item in all_data:
        gpt_val = item["conversations"][2]["value"]
        m = emotion_re.match(gpt_val)
        if m:
            tag = m.group(1)
            emotion_counter[tag] += 1
            if tag not in valid_emotions:
                missing_tag += 1
        else:
            missing_tag += 1
        category_counter[item["category"]] += 1

    # 셔플 후 저장
    random.shuffle(all_data)
    with open(OUTPUT_PATH, "w", encoding="utf-8") as f:
        for item in all_data:
            f.write(json.dumps(item, ensure_ascii=False) + "\n")

    # ── 통계 출력 ─────────────────────────────────────────────────
    total = len(all_data)
    print(f"\n{'='*55}")
    print(f"  시온(sion) 대화 데이터셋 생성 완료")
    print(f"{'='*55}")
    print(f"  저장 위치: {OUTPUT_PATH}")
    print(f"  총 대화 쌍: {total:,}개")
    print(f"  감정 태그 누락: {missing_tag}개\n")

    print("  [카테고리별 분포]")
    for cat, cnt in sorted(category_counter.items(), key=lambda x: -x[1]):
        bar = "#" * (cnt // 3)
        print(f"  {cat:<12} {cnt:>4}개  {bar}")

    print("\n  [감정 태그 분포]")
    for emo, cnt in sorted(emotion_counter.items(), key=lambda x: -x[1]):
        bar = "#" * (cnt // 3)
        print(f"  {emo:<12} {cnt:>4}개  {bar}")

    print(f"\n{'='*55}\n")


if __name__ == "__main__":
    main()
